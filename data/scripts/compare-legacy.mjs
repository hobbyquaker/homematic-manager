/**
 * Compare `data/dist/profiles/` with the easy modes the 2.7.1 code shipped in
 * `legacy/www/easymodes/`, so that the switch to openccu-data is a measured decision and not a
 * hope. Writes `data/COMPARISON.md` and prints a summary.
 *
 * The legacy format is `<RECEIVER_TYPE>/<SENDER_TYPE>.json`:
 *   {"<profile id>": {"name": "<name key>", "params": {"<PARAM>": {"val": "4", "readonly": true}},
 *                     "options": {...}}}
 * `readonly` is the old spelling of a `fixed` constraint; a value without it was a pre-set the user
 * could still change, which is what a `list` or `range` constraint expresses today.
 */
import path from 'node:path';

import {resolveValues} from './lib/constraints.mjs';
import {hasLegacy, legacyProfiles, legacyReceiverTypes} from './lib/legacy.mjs';
import {dataDir, distDir} from './lib/paths.mjs';
import {writeMarkdown} from './lib/write-json.mjs';
import {readFileSync, readdirSync} from 'node:fs';

if (!hasLegacy()) {
    console.error('legacy/www/easymodes is gone - nothing to compare (that is expected once 3.0 ships)');
    process.exit(0);
}

const read = (relative) => JSON.parse(readFileSync(path.join(distDir, relative), 'utf8'));
const newReceivers = readdirSync(path.join(distDir, 'profiles'))
    .map((file) => file.slice(0, -'.json'.length))
    .sort();
const aliases = read('receiver-type-aliases.json');
const newProfiles = Object.fromEntries(newReceivers.map((type) => [type, read(`profiles/${type}.json`)]));
const oldReceivers = legacyReceiverTypes();

/** The 2.x values are Tcl too (`300 ;# Default 5 Minuten Garagenlicht`), so resolve both sides. */
const asNumber = (value) => {
    const resolved = resolveValues(value);
    return resolved.length === 1 ? resolved[0] : JSON.stringify(resolved);
};

const lines = [];
const say = (line = '') => lines.push(line);

say('# What the openccu-data switch changes');
say();
say('Generated by `npm run compare-legacy` in `data/`. It compares the committed `data/dist/profiles/`');
say('with `legacy/www/easymodes/`, the 28 receiver types the 2.x code converted by hand in 2015-2019.');
say();

// ---------------------------------------------------------------- coverage

const onlyLegacy = oldReceivers.filter((type) => !newReceivers.includes(type));
const gained = newReceivers.filter((type) => !oldReceivers.includes(type));

let oldCombinations = 0;
let oldProfileCount = 0;
for (const receiverType of oldReceivers) {
    const senders = legacyProfiles(receiverType);
    oldCombinations += Object.keys(senders).length;
    for (const profiles of Object.values(senders)) oldProfileCount += Object.keys(profiles).length;
}
let newCombinations = 0;
let newProfileCount = 0;
for (const file of Object.values(newProfiles)) {
    newCombinations += Object.keys(file.senders).length;
    for (const list of Object.values(file.senders)) newProfileCount += list.length;
}

say('## Coverage');
say();
say('| | 2.7.1 (`legacy/www/easymodes`) | 3.0 (`data/dist/profiles`) |');
say('| --- | --- | --- |');
say(`| receiver types | ${oldReceivers.length} | ${newReceivers.length} (+ ${Object.keys(aliases).length} aliases) |`);
say(`| receiver/sender combinations | ${oldCombinations} | ${newCombinations} |`);
say(`| link profiles | ${oldProfileCount} | ${newProfileCount} |`);
say('| languages | de, en, tr | de, en, tr (tr from the 2.x files) |');
say();
say(
    onlyLegacy.length === 0
        ? 'Every 2.x receiver type is covered by the new data; nothing was lost at the receiver level.'
        : `Receiver types only in 2.x: ${onlyLegacy.join(', ')}.`,
);
say();
say(`${gained.length} receiver types are new, among them every HomematicIP one (issue #50):`);
say();
say(gained.map((type) => `\`${type}\``).join(', ') + '.');
say();

// ---------------------------------------------------------------- per receiver

const missingCombinations = [];
const gainedCombinations = [];
const details = [];
let sharedProfiles = 0;
let identicalProfiles = 0;
let missingProfiles = 0;
let addedProfiles = 0;
let paramOnlyLegacy = 0;
let paramOnlyNew = 0;
let paramValueDiffers = 0;
let paramDerivable = 0;

/**
 * `UI_HINT` is the profile id (see `LinkProfile.id`), `UI_TEMPLATE` and `UI_DESCRIPTION` were the
 * WebUI's way of pointing at the profile's text. All three are derivable from the profile itself,
 * which is why openccu-data does not carry them; the writer (task 6) still has to send `UI_HINT`.
 */
const DERIVABLE = new Set(['UI_HINT', 'UI_TEMPLATE', 'UI_DESCRIPTION']);

for (const receiverType of oldReceivers) {
    const oldSenders = legacyProfiles(receiverType);
    const file = newProfiles[receiverType];
    if (!file) continue;
    const receiverNotes = [];

    for (const senderType of Object.keys(oldSenders).sort()) {
        if (!file.senders[senderType]) {
            missingCombinations.push(`${receiverType}/${senderType}`);
            continue;
        }
        const byId = new Map(file.senders[senderType].map((profile) => [profile.id, profile]));
        for (const [rawId, oldProfile] of Object.entries(oldSenders[senderType])) {
            const id = Number(rawId);
            const current = byId.get(id);
            if (!current) {
                missingProfiles += 1;
                receiverNotes.push(`- \`${senderType}\` profile ${id} (\`${oldProfile.name}\`) has no counterpart`);
                continue;
            }
            sharedProfiles += 1;
            if (oldProfile.name && current.key !== oldProfile.name) {
                receiverNotes.push(
                    `- \`${senderType}\` profile ${id}: key \`${oldProfile.name}\` is now \`${current.key}\``,
                );
            }
            const oldParams = oldProfile.params ?? {};
            const newParams = current.params ?? {};
            const missingHere = Object.keys(oldParams).filter((name) => !(name in newParams));
            paramDerivable += missingHere.filter((name) => DERIVABLE.has(name)).length;
            const onlyOld = missingHere.filter((name) => !DERIVABLE.has(name));
            const onlyNew = Object.keys(newParams).filter((name) => !(name in oldParams));
            const differing = [];
            for (const [name, value] of Object.entries(oldParams)) {
                const constraint = newParams[name];
                if (!constraint || constraint.kind !== 'fixed') continue;
                if (asNumber(value.val) !== constraint.value) {
                    differing.push(`${name} ${JSON.stringify(value.val)} -> ${JSON.stringify(constraint.value)}`);
                }
            }
            paramOnlyLegacy += onlyOld.length;
            paramOnlyNew += onlyNew.length;
            paramValueDiffers += differing.length;
            if (onlyOld.length === 0 && onlyNew.length === 0 && differing.length === 0) {
                identicalProfiles += 1;
                continue;
            }
            const parts = [];
            if (onlyOld.length > 0) parts.push(`only in 2.x: ${onlyOld.join(', ')}`);
            if (onlyNew.length > 0) parts.push(`new: ${onlyNew.join(', ')}`);
            if (differing.length > 0) parts.push(`changed: ${differing.join('; ')}`);
            receiverNotes.push(`- \`${senderType}\` profile ${id} (\`${current.key}\`): ${parts.join(' / ')}`);
        }
    }

    for (const senderType of Object.keys(file.senders).sort()) {
        if (!oldSenders[senderType]) {
            gainedCombinations.push(`${receiverType}/${senderType}`);
            addedProfiles += file.senders[senderType].length;
        }
    }

    if (receiverNotes.length > 0) {
        details.push(`### ${receiverType}`, '', ...receiverNotes, '');
    }
}

say('## The 28 receiver types the 2.x code had');
say();
say(`- ${sharedProfiles} profiles exist in both; ${identicalProfiles} of them are parameter-identical.`);
say(`- ${missingProfiles} 2.x profiles have no counterpart in the new data.`);
say(
    `- ${missingCombinations.length} receiver/sender combinations were lost, ` +
        `${gainedCombinations.length} were gained within those 28 receivers (${addedProfiles} profiles).`,
);
say(
    `- Parameter differences across the shared profiles: ${paramOnlyLegacy} only in 2.x, ` +
        `${paramOnlyNew} only in the new data, ${paramValueDiffers} with a different fixed value.`,
);
say(
    `- Another ${paramDerivable} 2.x entries are \`UI_HINT\`, \`UI_TEMPLATE\` and \`UI_DESCRIPTION\`, which ` +
        'openccu-data leaves out because they are derivable from the profile itself. `UI_HINT` is the ' +
        'profile id and the writer still has to send it - see `LinkProfile.id`.',
);
say();
if (missingCombinations.length > 0) {
    say('Lost combinations:');
    say();
    say(missingCombinations.map((entry) => `\`${entry}\``).join(', ') + '.');
    say();
}
if (gainedCombinations.length > 0) {
    say('Gained combinations inside the 28 receivers:');
    say();
    say(gainedCombinations.map((entry) => `\`${entry}\``).join(', ') + '.');
    say();
}

say('## What the new data does not carry');
say();
say('- The per-profile `options` block of the 2.x files (which parameter the dialog offers as a');
say('  dropdown for *this* profile). openccu-data flattened it to one list per sender type, which is');
say('  kept as `ReceiverProfiles.senderMetadata`; the per-profile granularity is gone.');
say('- The `input` hints of those options (`EnterTime_h_m_s`, `EnterPercent`). The paramset');
say('  description (`TYPE`, `UNIT`, `MIN`, `MAX`) carries the same information, so task 8 can derive');
say('  the editor from the description instead of from a hard-coded hint.');
say('- `UI_DEFINITION_1_1` / `_1_2`, the radio-button labels of four profiles ("gekippt oder ganz');
say('  offen"). openccu-data drops them too.');
say();
say('## Per-receiver differences');
say();
say(...(details.length > 0 ? [details.join('\n')] : ['None.']));

await writeMarkdown(path.join(dataDir, 'COMPARISON.md'), lines.join('\n').replace(/\n{3,}/gu, '\n\n') + '\n');

console.log(
    `data/COMPARISON.md written: ${oldReceivers.length} -> ${newReceivers.length} receiver types, ` +
        `${oldProfileCount} -> ${newProfileCount} profiles; ${missingCombinations.length} lost and ` +
        `${gainedCombinations.length} gained sender combinations inside the 28 legacy receivers, ` +
        `${missingProfiles} lost profiles, ${identicalProfiles}/${sharedProfiles} shared profiles identical`,
);
